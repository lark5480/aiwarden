-- V10：M4 / P5 Agent Checkpoint + 版本 CAS（FR-CKPT-01~04）+ 全链路 Trace 关联列
-- 说明：
--   * t_agent_session 一次「运行」（run）一行：外部 session_key 可重复（同一会话的多次问答）；
--     resume 取该 session_key 下最新的 RUNNING/ABORTED 行，运行身份靠主键 id；
--   * t_agent_step 每步完成落一行（输入/输出快照 + 版本号），step_no 在 run 内唯一；
--   * 版本 CAS：完成一步时 `UPDATE t_agent_session ... WHERE version = ?`，冲突即拒绝（FR-CKPT-03）；
--   * owner / lease_until：同一 run 只允许一个执行实例推进；崩溃实例的租约过期后由续跑实例接管；
--   * trace_parent 落在 outbox 事件上（发送在定时任务里，晚于产生它的请求——必须在写入时捕获）。

ALTER TABLE t_outbox_event ADD COLUMN trace_parent VARCHAR(128);
ALTER TABLE t_llm_call_log ADD COLUMN trace_id VARCHAR(32);

CREATE TABLE t_agent_session (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT       NOT NULL,
    user_id       BIGINT       NOT NULL,
    org_id        BIGINT,
    session_key   VARCHAR(64)  NOT NULL,       -- 外部会话标识（ChatAskRequest.sessionId；可重复）
    request       JSONB        NOT NULL,       -- 原始请求快照（续跑时不依赖客户端）
    status        VARCHAR(16)  NOT NULL DEFAULT 'RUNNING',  -- RUNNING/SUCCEEDED/DENIED/FAILED/ABORTED
    last_step_no  INT          NOT NULL DEFAULT 0,
    version       INT          NOT NULL DEFAULT 0,
    owner         VARCHAR(64),                 -- 当前执行实例（租约持有者）
    lease_until   TIMESTAMPTZ,
    trace_id      VARCHAR(32),
    trace_parent  VARCHAR(128),                -- 运行开始时的 W3C traceparent（续跑接回同一条链）
    outcome       VARCHAR(32),
    reason        TEXT,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_t_agent_session_key ON t_agent_session (tenant_id, session_key, id DESC);
CREATE INDEX idx_t_agent_session_lease ON t_agent_session (status, lease_until);

CREATE TABLE t_agent_step (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL,
    session_id BIGINT      NOT NULL REFERENCES t_agent_session (id),
    step_no    INT         NOT NULL,
    name       VARCHAR(64) NOT NULL,
    input      JSONB,
    output     JSONB,
    detail     VARCHAR(512),
    elapsed_ms BIGINT      NOT NULL DEFAULT 0,
    status     VARCHAR(16) NOT NULL,           -- SUCCEEDED
    version    INT         NOT NULL,           -- 完成该步后的 run 版本（CAS 后的值）
    trace_id   VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_t_agent_step_session_step UNIQUE (session_id, step_no)
);

CREATE INDEX idx_t_agent_step_trace ON t_agent_step (trace_id);
