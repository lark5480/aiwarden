-- V9：评测报告（M3 / ADR-012；FR-ADM-05 评测报告页的数据源）
-- 一次 `mvn verify` 的评测门禁运行写一条（全栈门禁驱动在 aiwarden-start/src/test 的
-- ChatEvalGateContainersTest）；detail 为逐样本结论明细（JSONB，含每条样本的
-- expect/actual outcome、failures、latency、cost）。
CREATE TABLE t_eval_report (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    total             INT            NOT NULL,
    passed            INT            NOT NULL,
    deny_total        INT            NOT NULL,
    deny_blocked      INT            NOT NULL,
    duplicate_tickets INT            NOT NULL,
    p95_latency_ms    BIGINT         NOT NULL,
    avg_cost          NUMERIC(12, 6) NOT NULL,
    detail            JSONB          NOT NULL
);
